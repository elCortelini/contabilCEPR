export function importarTurmasEAlunosOficiais() {
  console.log('🔄 Iniciando importação das 35 turmas e alunos oficiais (101 a 803)...');

  const insertTurma = db.prepare(`
    INSERT INTO turmas (nome, anoLetivo, turno) VALUES (?, '2026', ?)
  `);

  const insertAluno = db.prepare(`
    INSERT INTO alunos (nome, turmaId, responsavel, contato, status) VALUES (?, ?, ?, '', 'ativo')
  `);

  const findTurma = db.prepare('SELECT id FROM turmas WHERE nome = ?');

  const transaction = db.transaction(() => {
    // Limpar turmas legadas/mock que não sejam o formato numérico 101 a 803
    const turmasAntigas = db.prepare("SELECT id FROM turmas WHERE nome NOT GLOB '[1-8][0-9][0-9]'").all() as any[];
    for (const t of turmasAntigas) {
      db.prepare('DELETE FROM alunos WHERE turmaId = ?').run(t.id);
      db.prepare('DELETE FROM turmas WHERE id = ?').run(t.id);
    }

    let totalAlunosInseridos = 0;
    let turmasProcessadas = 0;

    for (const grupo of DADOS_TURMAS_ALUNOS) {
      let turmaRow = findTurma.get(grupo.turma) as any;
      let turmaId: number;

      if (!turmaRow) {
        const resTurma = insertTurma.run(grupo.turma, grupo.turno);
        turmaId = Number(resTurma.lastInsertRowid);
      } else {
        turmaId = Number(turmaRow.id);
      }

      turmasProcessadas++;

      // Inserir alunos da turma evitando duplicar
      const checkAluno = db.prepare('SELECT id FROM alunos WHERE nome = ? AND turmaId = ?');

      for (const al of grupo.alunos) {
        const existe = checkAluno.get(al.nome, turmaId);
        if (!existe) {
          insertAluno.run(al.nome, turmaId, al.responsavel || '');
          totalAlunosInseridos++;
        }
      }
    }

    return { turmasProcessadas, totalAlunosInseridos };
  });

  const resultado = transaction();
  console.log(`✅ Importação concluída: ${resultado.turmasProcessadas} turmas e ${resultado.totalAlunosInseridos} alunos sincronizados.`);
  return resultado;
}
